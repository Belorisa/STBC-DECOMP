/*
================
TGHashString

Hashes a name: four chained table lookups, one per byte of the result, the
first table giving the top byte.
================
*/
// FUNCTION: STBC 0x007202e0
int TGHashString( char *string ) {
	char *end = string;
	while ( *end ) {
		end++;
	}

	unsigned int hash3 = 0;
	unsigned int hash2 = 0;
	unsigned int hash1 = 0;
	unsigned int hash0 = 0;
	for ( ; string != end; string++ ) {
		hash0 = hashTable0[ *string ^ hash0 ];
		hash1 = hashTable1[ *string ^ hash1 ];
		hash2 = hashTable2[ *string ^ hash2 ];
		hash3 = hashTable3[ *string ^ hash3 ];
	}
	return ( ( ( hash0 << 8 ) + hash1 << 8 ) + hash2 << 8 ) + hash3;
}
