/*
================
TGSystemModule::VirtualSlot00

Reads the trace configuration, gives the system wrapper the render window
and the renderer, and seeds the random numbers with the time.
================
*/
// FUNCTION: STBC 0x715FF0
// DRAFT: schedule: retail sets the renderer temporary's EH state right after pushing it and loads the app window into ECX; this build loads it into ESI before the state store
void TGSystemModule::VirtualSlot00( void ) {
	TGTraceStream::LoadConfiguration();
	UtopiaApp *app = UtopiaApp::GetApp();
	g_kSystemWrapper.Unknown71A970( app->GetAppWindow()->GetRenderWindow(), app->GetRenderer() );
	g_kSystemWrapper.SetRandomSeed( timeGetTime() );
}

/*
================
TGSystemModule::VirtualSlot05

Ends the profiling and deletes the trace outputs.
================
*/
// FUNCTION: STBC 0x716090
void TGSystemModule::VirtualSlot05( void ) {
	TGProfilingInfo::Terminate();
	TGTraceStream::DeleteOutputs();
}
