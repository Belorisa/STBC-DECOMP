/*
================
TGIconGroupRegistration::TGIconGroupRegistration

Keeps a copy of each string.
================
*/
// FUNCTION: STBC 0x00747990 ??0TGIconGroupRegistration@@QAE@PAD00@Z
TGIconGroupRegistration::TGIconGroupRegistration( char *name_, char *module_, char *function_ ) {
	name = new char[strlen( name_ ) + 1];
	strcpy( name, name_ );
	module = new char[strlen( module_ ) + 1];
	strcpy( module, module_ );
	function = new char[strlen( function_ ) + 1];
	strcpy( function, function_ );
}

/*
================
TGIconGroupRegistration::~TGIconGroupRegistration
================
*/
// FUNCTION: STBC 0x00747a60
TGIconGroupRegistration::~TGIconGroupRegistration( void ) {
	if ( name != NULL ) {
		delete name;
	}
	if ( module != NULL ) {
		delete module;
	}
	if ( function != NULL ) {
		delete function;
	}
}

/*
================
TGIconGroupRegistration::WriteToStream

The group's name, the script module and the function.
================
*/
// FUNCTION: STBC 0x00747aa0
bool TGIconGroupRegistration::WriteToStream( TGStream *stream ) {
	stream->VirtualSlot11( name );
	stream->VirtualSlot11( module );
	stream->VirtualSlot11( function );
	return true;
}

/*
================
TGIconGroupRegistration::ReadFromStream

Reads what WriteToStream wrote.
================
*/
// FUNCTION: STBC 0x00747ad0
bool TGIconGroupRegistration::ReadFromStream( TGStream *stream ) {
	name = stream->VirtualSlot10( -1 );
	module = stream->VirtualSlot10( -1 );
	function = stream->VirtualSlot10( -1 );
	return true;
}
