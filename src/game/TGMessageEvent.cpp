// FUNCTION: STBC 0x006bfe80 ??0TGMessageEvent@@QAE@XZ
TGMessageEvent::TGMessageEvent( void ) {
	message = NULL;
}

/*
================
TGMessageEvent::~TGMessageEvent
================
*/
// FUNCTION: STBC 0x006bfea0 ??1TGMessageEvent@@UAE@XZ
TGMessageEvent::~TGMessageEvent( void ) {
	if ( message != NULL ) {
		delete message;
		message = NULL;
	}
}

/*
================
TGMessageEvent::Copy

The copy gets its own copy of the message.
================
*/
// FUNCTION: STBC 0x006bff00
bool TGMessageEvent::Copy( TGEvent *event ) {
	TGMessageEvent *other = (TGMessageEvent *)event;
	if ( other->message != NULL ) {
		SetMessage( other->message->Copy() );
	}
	return TGEvent::Copy( event );
}

/*
================
TGMessageEvent::SetMessage

The event owns its message: the old one is deleted.
================
*/
// FUNCTION: STBC 0x006bff30
void TGMessageEvent::SetMessage( TGMessage *message_ ) {
	if ( message != NULL ) {
		delete message;
	}
	message = message_;
}
