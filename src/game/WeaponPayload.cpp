// DATA: STBC 0x0098eed4
long WeaponPayload::nextID;

/*
================
WeaponPayload::WeaponPayload

Takes the next ID.
================
*/
// FUNCTION: STBC 0x005b95a0
WeaponPayload::WeaponPayload( void ) {
	id = nextID++;
	payloadType = WP_DEFAULT;
	damageRadiusFactor = 1.0f;
}

/*
================
WeaponPayload::WriteToStream
================
*/
// FUNCTION: STBC 0x005b95d0
bool WeaponPayload::WriteToStream( TGStream *stream ) {
	stream->WriteID( id );
	stream->WriteLong( payloadType );
	stream->WriteFloat( damageRadiusFactor );
	return true;
}

/*
================
WeaponPayload::ReadFromStream
================
*/
// FUNCTION: STBC 0x005b9610
bool WeaponPayload::ReadFromStream( TGStream *stream ) {
	id = stream->ReadID();
	payloadType = stream->ReadLong();
	damageRadiusFactor = stream->ReadFloat();
	return true;
}
